/**
 * 五子棋核心类型定义
 * ------------------------------------------------------------------
 * 本文件只约定"数据长什么样"，不包含任何规则实现。
 * 逻辑层（logic/rules.ts）、UI 层（components/）和 AI（logic/ai/）
 * 都从这里导入类型，保证三方对棋盘的认知完全一致。
 *
 * 说明：项目 tsconfig 开启了 `erasableSyntaxOnly`，
 * 因此这里不使用 enum（enum 会生成运行时代码），
 * 而是统一使用字符串字面量联合类型 —— 类型更精确、可读性也更好。
 */

/**
 * 玩家 / 棋子颜色。
 * - 'black'：黑棋（通常先手）
 * - 'white'：白棋
 */
export type Player = 'black' | 'white'

/**
 * 棋盘上单个交叉点的状态。
 * - 'empty'：空点，可以落子
 * - 'black' / 'white'：已被对应颜色的棋子占据
 *
 * 这里复用 Player，而不是把三种状态重新写一遍，
 * 好处是将来给 Player 扩展（例如加入 'red'）时只需改一处。
 * 若还需要"禁手点"等特殊状态，也只在本类型里追加即可。
 */
export type CellState = 'empty' | Player

/**
 * 棋盘坐标，表示两条线的交叉点（不是格子中心）。
 * - x：列号，从左往右，取值范围 0 ~ BOARD_SIZE - 1
 * - y：行号，从上往下，取值范围 0 ~ BOARD_SIZE - 1
 *
 * 使用对象而非数组，是为了让 `board[y][x]` 的取值点更直观，
 * 避免把 x / y 顺序写反这类常见 bug。
 */
export interface Position {
  x: number
  y: number
}

/**
 * 棋盘数据结构：二维数组，按"行"存储。
 *
 * 访问方式是 `board[y][x]`：
 * - 第一维是行（y），第二维是列（x）；
 * - board[0] 是最上面一行，board[0][0] 是左上角交叉点。
 *
 * 选择"先行后列"，是为了和棋盘的视觉顺序一致：
 * 渲染时按行走、按列画，天然对应双重循环。
 *
 * 注意：这里把 Board 定义成可变二维数组，
 * 因为对局过程中会原地写入落子；如果需要不可变数据
 * （例如 AI 搜索时做快照），请在逻辑层自行复制，而不是改类型。
 */
export type Board = CellState[][]
